    // The contacts currently listed in jList1, in the same order as the rows
    private final java.util.List<model.Contact> shownContacts = new java.util.ArrayList<>();

    // How the list is sorted (changed from the right-click menu on the list)
    private java.util.Comparator<model.Contact> currentSort = model.Contact.BY_NAME;

    // Extra set-up done once when the window opens
    private void setUpExtras() {
        
        showContactListArea();

        jList1.setSelectionMode(javax.swing.ListSelectionModel.SINGLE_SELECTION);

        // The Delete button acts on the contact selected in the list
        jButton4.addActionListener(evt -> deleteSelectedContact());

        jButton5.addActionListener(evt -> logout());

        // Right-click the list to choose how it is sorted
        javax.swing.JPopupMenu sortMenu = new javax.swing.JPopupMenu();
        addSortItem(sortMenu, "Sort by name (A-Z)", model.Contact.BY_NAME);
        addSortItem(sortMenu, "Sort by phone number", model.Contact.BY_PHONE);
        addSortItem(sortMenu, "Sort by date added (oldest first)", model.Contact.BY_DATE_ADDED);
        addSortItem(sortMenu, "Sort by date added (newest first)", model.Contact.BY_DATE_ADDED.reversed());
        jList1.setComponentPopupMenu(sortMenu);
    }

    // Puts the list in the middle of the scroll area of the form, with the
    // Edit and Delete buttons underneath it.
    private void showContactListArea() {
        javax.swing.JLabel hint = new javax.swing.JLabel(
            "Name | Phone | Email  -  select a contact, then Edit or Delete (right-click the list to sort)");
        hint.setBorder(javax.swing.BorderFactory.createEmptyBorder(6, 8, 6, 8));

        javax.swing.JPanel buttonBar = new javax.swing.JPanel(
            new java.awt.FlowLayout(java.awt.FlowLayout.RIGHT, 8, 6));
        buttonBar.add(jButton3); // Edit
        buttonBar.add(jButton4); // Delete

        FitPanel area = new FitPanel(new java.awt.BorderLayout());
        area.add(hint, java.awt.BorderLayout.NORTH);
        area.add(jScrollPane2, java.awt.BorderLayout.CENTER);
        area.add(buttonBar, java.awt.BorderLayout.SOUTH);

        jScrollPane1.setViewportView(area);
    }

    // A panel that always matches the size of its scroll area, so it never needs
    // scroll bars of its own (the list inside it scrolls instead).
    private static class FitPanel extends javax.swing.JPanel implements javax.swing.Scrollable {
        FitPanel(java.awt.LayoutManager layout) {
            super(layout);
        }

        @Override
        public java.awt.Dimension getPreferredScrollableViewportSize() {
            return getPreferredSize();
        }

        @Override
        public int getScrollableUnitIncrement(java.awt.Rectangle visible, int orientation, int direction) {
            return 16;
        }

        @Override
        public int getScrollableBlockIncrement(java.awt.Rectangle visible, int orientation, int direction) {
            return 64;
        }

        @Override
        public boolean getScrollableTracksViewportWidth() {
            return true;
        }

        @Override
        public boolean getScrollableTracksViewportHeight() {
            return true;
        }
    }

    private void addSortItem(javax.swing.JPopupMenu menu, String text,
                             java.util.Comparator<model.Contact> order) {
        javax.swing.JMenuItem item = new javax.swing.JMenuItem(text);
        item.addActionListener(evt -> {
            currentSort = order;
            showContacts(shownContacts); // re-sorts what is currently shown
        });
        menu.add(item);
    }

    // Called by NewContact after a save, so this window shows the change
    public void refreshContacts() {
        jTextField1.setText(""); // clear the search box so nothing is filtered out
        loadAndSortContacts();
    }

    // Shows all contacts in the current sort order
    private void loadAndSortContacts() {
        try {
            showContacts(service.ContactManager.getInstance().viewAllContacts());
        } catch (persistance.PersistanceException e) {
            showStorageError(e);
        }
    }

    // Search button: matches the name, phone number or email
    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {
        String query = jTextField1.getText().trim();

        try {
            java.util.List<model.Contact> results =
                service.ContactManager.getInstance().search(query);

            showContacts(results);

            if (results.isEmpty() && !query.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this,
                    "No contacts match \"" + query + "\".",
                    "No Results",
                    javax.swing.JOptionPane.INFORMATION_MESSAGE);
            }
        } catch (persistance.PersistanceException e) {
            showStorageError(e);
        }
    }

    // Fills jList1 with one line per contact, sorted by currentSort
    private void showContacts(java.util.List<model.Contact> contacts) {
        java.util.List<model.Contact> sorted = new java.util.ArrayList<>(contacts);
        sorted.sort(currentSort);

        shownContacts.clear();
        shownContacts.addAll(sorted);

        javax.swing.DefaultListModel<String> listModel = new javax.swing.DefaultListModel<>();
        for (model.Contact c : shownContacts) {
            listModel.addElement(c.getName() + " | " + c.getPhone() + " | " + c.getEmail());
        }
        if (shownContacts.isEmpty()) {
            listModel.addElement("(no contacts to show)");
        }
        jList1.setModel(listModel);
    }

    // The contact selected in the list, or null if nothing is selected
    private model.Contact selectedContact() {
        int row = jList1.getSelectedIndex();
        return (row >= 0 && row < shownContacts.size()) ? shownContacts.get(row) : null;
    }

    private void editSelectedContact() {
        model.Contact selected = selectedContact();
        if (selected == null) {
            javax.swing.JOptionPane.showMessageDialog(this,
                "Select a contact in the list first.",
                "No Contact Selected",
                javax.swing.JOptionPane.INFORMATION_MESSAGE);
            return;
        }
        new NewContact(this, selected).setVisible(true);
    }

    private void deleteSelectedContact() {
        model.Contact selected = selectedContact();
        if (selected == null) {
            javax.swing.JOptionPane.showMessageDialog(this,
                "Select a contact in the list first.",
                "No Contact Selected",
                javax.swing.JOptionPane.INFORMATION_MESSAGE);
            return;
        }

        int answer = javax.swing.JOptionPane.showConfirmDialog(this,
            "Delete " + selected.getName() + " (" + selected.getPhone() + ")?",
            "Confirm Delete",
            javax.swing.JOptionPane.YES_NO_OPTION,
            javax.swing.JOptionPane.WARNING_MESSAGE);

        if (answer != javax.swing.JOptionPane.YES_OPTION) {
            return;
        }

        try {
            service.ContactManager.getInstance().deleteContactById(selected.getId());
            refreshContacts();
        } catch (service.InvalidContactException e) {
            javax.swing.JOptionPane.showMessageDialog(this,
                e.getMessage(),
                "Delete Failed",
                javax.swing.JOptionPane.WARNING_MESSAGE);
            refreshContacts();
        } catch (persistance.PersistanceException e) {
            showStorageError(e);
        }
    }

    private void logout() {
        new LoginPage().setVisible(true);
        this.dispose();
    }

    private void showStorageError(persistance.PersistanceException e) {
        javax.swing.JOptionPane.showMessageDialog(this,
            e.getMessage(),
            "Storage Error",
            javax.swing.JOptionPane.ERROR_MESSAGE);
    }

